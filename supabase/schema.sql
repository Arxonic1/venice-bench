-- venice-bench results table. Run in Supabase SQL editor or via psql.
create table if not exists public.venice_bench_results (
  id bigint generated by default as identity primary key,
  run_id text not null,
  suite text not null,
  model text not null,
  started_at timestamptz not null,
  finished_at timestamptz not null,
  runs int not null,
  passed int not null,
  failed int not null,
  pass_rate numeric not null,
  latency jsonb not null,
  tokens jsonb not null,
  cost jsonb not null,
  suite_metrics jsonb not null default '{}'::jsonb,
  trials jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists venice_bench_results_model_suite_idx
  on public.venice_bench_results (model, suite, started_at desc);

create index if not exists venice_bench_results_run_id_idx
  on public.venice_bench_results (run_id);
